#!/usr/bin/env node
/**
 * sync-fx-snapshot.mjs — refresh the honest FX offline fallback.
 *
 * Fetches CoinGecko (no key) BTC/USD + ECB daily fiat-fiat and rewrites:
 *   - public/research/fx-snapshot.json  (the app's step-3 offline fallback)
 *   - src/data/btcPriceAtCapture.ts      (the BTC-first sats anchor)
 *
 * Run after any dataset re-capture, or nightly via the pipeline:
 *   npm run fx:sync
 *
 * Honesty: the app never fakes a rate — this only updates the last-known-good
 * snapshot that the UI marks as stale when live feeds are down.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const FIATS = ['USD', 'EUR', 'GBP', 'CHF', 'JPY', 'INR', 'CAD', 'AUD']

async function main() {
  const [cg, ecb] = await Promise.all([
    fetch('https://api.coingecko.com/api/v3/simple/price?ids=bitcoin&vs_currencies=usd').then((r) => r.json()),
    fetch('https://www.ecb.europa.eu/stats/eurofxref/eurofxref-daily.xml').then((r) => r.text()),
  ])

  const btcUsd = cg?.bitcoin?.usd
  if (typeof btcUsd !== 'number' || btcUsd <= 0) {
    console.error('sync-fx-snapshot: CoinGecko BTC/USD missing — aborting, snapshot untouched.')
    process.exit(1)
  }

  const perEur = { EUR: 1 }
  const dateMatch = ecb.match(/<Cube time='([^']+)'/)
  const ecbDate = dateMatch?.[1] ?? 'unknown'
  const re = /<Cube currency='([A-Z]{3})' rate='([0-9.]+)'/g
  let m
  while ((m = re.exec(ecb))) {
    const code = m[1]
    const rate = Number(m[2])
    if (FIATS.includes(code) && rate > 0) perEur[code] = rate
  }
  const missing = FIATS.filter((f) => perEur[f] == null)
  if (missing.length > 0) {
    console.error(`sync-fx-snapshot: ECB missing rates for ${missing.join(', ')} — aborting.`)
    process.exit(1)
  }

  const capturedAt = new Date().toISOString()
  const snapshot = {
    captured_at: capturedAt,
    btc_usd: btcUsd,
    per_eur: perEur,
    source: `coingecko (BTC/USD) + ECB daily eurofxref ${ecbDate} (fiat-fiat)`,
  }

  const snapshotPath = resolve(ROOT, 'public/research/fx-snapshot.json')
  writeFileSync(snapshotPath, `${JSON.stringify(snapshot, null, 2)}\n`)

  const ts = `/**
 * BTC-first currency data anchor — AUTO-GENERATED by scripts/sync-fx-snapshot.mjs.
 * Do not edit by hand; re-run \`npm run fx:sync\` after dataset re-capture.
 */
export const BTC_USD_AT_CAPTURE = ${btcUsd}
export const CAPTURE_PRICE_SOURCE = 'coingecko' as const
export const CAPTURED_AT = '${capturedAt}'
`
  writeFileSync(resolve(ROOT, 'src/data/btcPriceAtCapture.ts'), ts)

  console.log(`sync-fx-snapshot: OK — BTC/USD ${btcUsd}, ECB ${ecbDate}, ${FIATS.length} fiats. Wrote snapshot + anchor.`)
}

main().catch((err) => {
  console.error('sync-fx-snapshot: failed', err)
  process.exit(1)
})
