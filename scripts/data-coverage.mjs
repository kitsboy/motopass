#!/usr/bin/env node
/**
 * Country data coverage audit.
 *
 * Reads research/countries.json and reports, for every program, which facts the
 * Programs page can show and which are still empty. It counts fields already on
 * file. It writes nothing, adds no facts, and makes no network calls.
 *
 *   node scripts/data-coverage.mjs            markdown report
 *   node scripts/data-coverage.mjs --json     machine-readable report
 */
import { readFileSync } from 'node:fs'

const catalog = JSON.parse(readFileSync(new URL('../research/countries.json', import.meta.url), 'utf8'))
const programs = Array.isArray(catalog) ? catalog : (catalog.programs ?? catalog.countries)

const hasText = value => typeof value === 'string' && value.trim().length > 0
const hasNumber = value => typeof value === 'number' && Number.isFinite(value)
const feeStated = value => hasText(value) && !/^unknown\b/i.test(value.trim())

/** Facts the Programs page prints, and what "on file" means for each. */
function facts(program) {
  return [
    { key: 'processing_time', have: hasText(program.finance?.processing_time_months) },
    { key: 'gov_fees', have: hasNumber(program.finance?.gov_fees_usd) },
    { key: 'tax_sentence', have: hasText(program.finance?.tax_benefits) },
    { key: 'crypto_tax_sentence', have: /Crypto\/Bitcoin tax:/i.test(program.finance?.tax_benefits ?? '') },
    { key: 'fee_in_bitcoin', have: feeStated(program.finance?.bitcoin_specific) },
    { key: 'days_in_country', have: hasNumber(program.compliance_clock?.residency_day_count_target) },
    { key: 'years_to_citizenship', have: hasNumber(program.compliance_clock?.citizenship_eligibility_years) },
    { key: 'renewal_months', have: hasNumber(program.compliance_clock?.renewal_interval_months) },
    { key: 'mobility', have: hasText(program.critical_tests?.notes) },
    { key: 'mobility_score', have: hasNumber(program.scorecard?.mobility) },
    { key: 'banking_score', have: hasNumber(program.scorecard?.banking) },
    { key: 'tax_score', have: hasNumber(program.scorecard?.tax) },
    { key: 'pathways', have: (program.pathways ?? []).length > 0 },
    { key: 'official_urls', have: (program.legal_compliance?.official_urls ?? []).length > 0 },
    { key: 'watched_urls', have: (program.watch?.urls ?? []).length > 0 },
    { key: 'sources_cited', have: (program.sources ?? []).length > 0 },
    { key: 'pros', have: (program.pros ?? []).length > 0 },
    { key: 'cons', have: (program.cons ?? []).length > 0 },
    { key: 'red_flags', have: (program.paige_fields?.red_flags ?? []).length > 0 },
    { key: 'optimization_tips', have: (program.paige_fields?.optimization_tips ?? []).length > 0 },
    { key: 'common_questions', have: (program.paige_fields?.common_questions ?? []).length > 0 },
    { key: 'property_ownership', have: hasText(program.legal_compliance?.property_foreign_ownership) },
    { key: 'recent_changes', have: hasText(program.legal_compliance?.recent_changes) },
  ]
}

const shape = program => ({
  name: program.name,
  detail_chars: (program.details ?? '').length,
  integration_chars: (program.bitcoin_integration ?? '').length,
  tax_chars: (program.finance?.tax_benefits ?? '').length,
  bitcoin_chars: (program.finance?.bitcoin_specific ?? '').length,
  sources: (program.sources ?? []).length,
  official_urls: (program.legal_compliance?.official_urls ?? []).length,
  watched_urls: (program.watch?.urls ?? []).length,
  pathways: (program.pathways ?? []).length,
  pros: (program.pros ?? []).length,
  cons: (program.cons ?? []).length,
  red_flags: (program.paige_fields?.red_flags ?? []).length,
  tips: (program.paige_fields?.optimization_tips ?? []).length,
  questions: (program.paige_fields?.common_questions ?? []).length,
  audit_rows: (program.audit_trail ?? []).length,
  facts_have: 0,
  facts_total: 0,
})

const rows = programs.map(program => {
  const list = facts(program)
  const row = shape(program)
  row.facts_have = list.filter(item => item.have).length
  row.facts_total = list.length
  return { row, list }
})

const gaps = rows[0].list.map((_, index) => {
  const key = rows[0].list[index].key
  const missing = rows.filter(entry => !entry.list[index].have).map(entry => entry.row.name)
  return { key, have: programs.length - missing.length, total: programs.length, missing }
})

const sorted = [...rows].sort((a, b) => a.row.facts_have - b.row.facts_have)

if (process.argv.includes('--json')) {
  console.log(JSON.stringify({ programs: programs.length, gaps, rows: rows.map(entry => entry.row) }, null, 1))
  process.exit(0)
}

const pad = (value, width) => String(value).padStart(width)
const out = []
out.push(`# Country data coverage — ${programs.length} programs`, '')
out.push('Generated by `npm run coverage:data`. It counts fields already in `research/countries.json`; it adds no facts.', '')
out.push('## Facts on file, by fact', '')
out.push('| Fact | On file | Missing |', '| --- | --- | --- |')
for (const gap of gaps) {
  out.push(`| \`${gap.key}\` | ${gap.have}/${gap.total} | ${gap.missing.length === 0 ? '—' : gap.missing.join(', ')} |`)
}
out.push('', '## Record depth, by country (thinnest first)', '')
out.push('| Country | Facts | Details | Integration | Tax | Bitcoin | Src | URLs | Paths | Pros | Cons | Flags | Tips | Q |')
out.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |')
for (const { row } of sorted) {
  out.push(
    `| ${row.name} | ${row.facts_have}/${row.facts_total} | ${pad(row.detail_chars, 4)} | ${pad(row.integration_chars, 4)} | ${pad(row.tax_chars, 4)} | ${pad(row.bitcoin_chars, 4)} | ${row.sources} | ${row.official_urls} | ${row.pathways} | ${row.pros} | ${row.cons} | ${row.red_flags} | ${row.tips} | ${row.questions} |`,
  )
}
console.log(out.join('\n'))
