/**
 * Auto-derive MotoPass build identity from git + build date.
 *
 * Single source of truth for the BUILD_* constants. This script:
 *   - computes BUILD_ID = `<YYYY.MM.DD>-<sha7>` (deterministic per commit, and
 *     robust to shallow clones where `git rev-list --count` yields 1),
 *     BUILD_DATE = build date, BUILD_LABEL = latest commit subject
 *   - writes src/lib/buildInfo.ts (imported by the app at compile time)
 *
 * It runs at build time on EVERY build path:
 *   - `npm run build`  → `node scripts/gen-build-info.mjs && vite build`
 *   - CI (`npx vite build`) → vite.config.ts buildStart plugin calls this too
 *
 * There is NO manually-maintained build tag anymore — the deployed tag always
 * matches the actual commit that produced it, so the footer, the ?v= cache
 * busters, and the vite output filename salt can never go stale.
 *
 * Run standalone:  node scripts/gen-build-info.mjs
 */
import { execSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = resolve(__dirname, '..')
const BUILD_INFO_PATH = resolve(root, 'src/lib/buildInfo.ts')

const pad = (n) => String(n).padStart(2, '0')

/** Compute the build identity from the current git state + build date. */
export function resolveBuild() {
  const now = new Date()
  const date = `${now.getFullYear()}.${pad(now.getMonth() + 1)}.${pad(now.getDate())}`

  let count = '0'
  let sha = '0000000'
  let label = 'autobuild'
  try {
    count = execSync('git rev-list --count HEAD', { cwd: root, encoding: 'utf8' }).trim()
    sha = execSync('git rev-parse --short=7 HEAD', { cwd: root, encoding: 'utf8' }).trim()
    label = execSync('git log -1 --pretty=%s', { cwd: root, encoding: 'utf8' }).trim().slice(0, 120)
  } catch {
    // Not a git checkout — fall back to a still-unique per-build tag.
    count = Date.now().toString(36)
    label = 'non-git build'
  }

  return { date, count, sha, label, id: `${date}-${sha}` }
}

/** Render the generated buildInfo.ts module contents. */
export function renderBuildInfo(b) {
  const safeLabel = b.label.replace(/[`$]/g, (c) => '\\' + c)
  return `/**
 * AUTO-GENERATED by scripts/gen-build-info.mjs at build time.
 * DO NOT EDIT MANUALLY — every build derives BUILD_ID from git + build date,
 * so the footer, ?v= cache busters, and vite filename salt can never go stale.
 * SHA: ${b.sha}
 */
export const BUILD_ID = '${b.id}'
export const BUILD_LABEL = \`${safeLabel}\`
export const BUILD_DATE = '${b.date}'
/** Shown in site footer — auto-synced with BUILD_ID */
export const FOOTER_VERSION = \`BUILD \${BUILD_ID}\`
`
}

// CLI entry: write buildInfo.ts when run as `node scripts/gen-build-info.mjs`.
const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  const b = resolveBuild()
  writeFileSync(BUILD_INFO_PATH, renderBuildInfo(b), 'utf8')
  console.log(`buildInfo.ts -> BUILD ${b.id} (${b.count} commits, ${b.sha})`)
}
